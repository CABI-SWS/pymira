"""Sparse tiled polyball meshing for large vascular graphs."""

from __future__ import annotations

from collections import defaultdict
from concurrent.futures import FIRST_COMPLETED, ThreadPoolExecutor, wait
import os
from pathlib import Path
import shutil
import tempfile

import numpy as np

from pymira.tube_mesh import _graph_segments, _update_union


_FACE_DTYPE = np.dtype([("count", "u1"), ("indices", "<i4", (3,))])


def _segment_intersects_expanded_tile(start, end, tile, expansion):
    """Conservatively test a segment against an expanded grid tile."""
    direction = end - start
    lower = np.asarray(tile, dtype=np.float64) - expansion
    upper = np.asarray(tile, dtype=np.float64) + 1.0 + expansion
    first, last = 0.0, 1.0
    for axis in range(3):
        delta = float(direction[axis])
        coordinate = float(start[axis])
        if abs(delta) < 1e-15:
            if coordinate < lower[axis] or coordinate > upper[axis]:
                return False
            continue
        enter = (lower[axis] - coordinate) / delta
        leave = (upper[axis] - coordinate) / delta
        if enter > leave:
            enter, leave = leave, enter
        first = max(first, enter)
        last = min(last, leave)
        if first > last:
            return False
    return True


def _tile_index(p0, p1, r0, r1, origin, grid_shape, spacing,
                tile_cells, blend_radius, max_tile_references):
    """Map sparse grid tiles to the segments which can influence them."""
    tiles = defaultdict(list)
    grid_last = np.asarray(grid_shape, dtype=np.int64) - 1
    references = 0
    tile_width = float(spacing) * int(tile_cells)
    for index, (start, end, start_radius, end_radius) in enumerate(
            zip(p0, p1, r0, r1)):
        influence = max(start_radius, end_radius) + blend_radius + 2.0 * spacing
        lower = np.maximum(
            0, np.floor((np.minimum(start, end) - influence - origin) /
                        spacing).astype(np.int64))
        upper = np.minimum(
            grid_last, np.ceil((np.maximum(start, end) + influence - origin) /
                               spacing).astype(np.int64))
        first_tile = lower // tile_cells
        last_tile = np.maximum(upper - 1, 0) // tile_cells
        start_tile_space = (start - origin) / tile_width
        end_tile_space = (end - origin) / tile_width
        expansion = float(influence) / tile_width
        for ix in range(int(first_tile[0]), int(last_tile[0]) + 1):
            for iy in range(int(first_tile[1]), int(last_tile[1]) + 1):
                for iz in range(int(first_tile[2]), int(last_tile[2]) + 1):
                    tile = (ix, iy, iz)
                    if not _segment_intersects_expanded_tile(
                            start_tile_space, end_tile_space, tile, expansion):
                        continue
                    references += 1
                    if references > max_tile_references:
                        raise MemoryError(
                            f"Sparse tile index would exceed "
                            f"{max_tile_references:,} segment references. "
                            "Increase tile_cells, increase voxel_size, or "
                            "export spatial partitions separately.")
                    tiles[tile].append(index)
    return tiles, references


def _boundary_key(grid_coordinate, local_coordinate, cell_shape,
                  tolerance=1e-5):
    """Return a stable key only for vertices shared by adjacent tiles."""
    boundary = np.any(np.isclose(local_coordinate, 0.0, atol=tolerance)) or \
        np.any(np.isclose(local_coordinate, cell_shape, atol=tolerance))
    if not boundary:
        return None
    return tuple(np.rint(grid_coordinate * 100000.0).astype(np.int64))


def _write_binary_ply(output, vertex_file, face_file, vertex_count, face_count):
    header = (
        "ply\n"
        "format binary_little_endian 1.0\n"
        "comment generated by pymira tiled hard-union polyball mesher\n"
        f"element vertex {vertex_count}\n"
        "property float x\nproperty float y\nproperty float z\n"
        f"element face {face_count}\n"
        "property list uchar int vertex_indices\n"
        "end_header\n").encode("ascii")
    with open(output, "wb") as destination:
        destination.write(header)
        with open(vertex_file, "rb") as source:
            shutil.copyfileobj(source, destination, length=16 * 1024 * 1024)
        with open(face_file, "rb") as source:
            shutil.copyfileobj(source, destination, length=16 * 1024 * 1024)


def _bounded_parallel_map(executor, function, iterable, max_pending):
    """Yield completed work promptly while keeping the queue bounded."""
    source = iter(iterable)
    pending = set()
    for _ in range(max_pending):
        try:
            pending.add(executor.submit(function, next(source)))
        except StopIteration:
            break
    while pending:
        completed, pending = wait(pending, return_when=FIRST_COMPLETED)
        for future in completed:
            yield future.result()
            try:
                pending.add(executor.submit(function, next(source)))
            except StopIteration:
                pass


def tiled_hard_union_to_ply(
        graph, ofile, edge_filter=None, min_radius=0.0, radius_scale=1.0,
        resolution=10, voxel_size=None, tile_cells=32,
        union_mode="hard", blend_radius=None,
        max_tile_references=50_000_000, tile_workers=None, verbose=True):
    """Stream a sparse tiled hard-union mesh directly to binary PLY."""
    from skimage.measure import marching_cubes

    if not ofile:
        raise ValueError("The tiled exporter requires an output filename")
    if tile_cells < 4:
        raise ValueError("tile_cells must be at least 4")
    aliases = {"hard": "hard", "hard_union": "hard",
               "smooth": "smooth", "smooth_union": "smooth"}
    if union_mode not in aliases:
        raise ValueError("union_mode must be 'hard' or 'smooth'")
    union_mode = aliases[union_mode]

    p0, p1, r0, r1 = _graph_segments(
        graph, edge_filter=edge_filter, min_radius=min_radius,
        radius_scale=radius_scale)
    if len(p0) == 0:
        return None
    minimum_radius = float(np.min(np.minimum(r0, r1)))
    maximum_radius = float(np.max(np.maximum(r0, r1)))
    if voxel_size is None:
        voxel_size = minimum_radius / max(3.0, float(resolution) / 3.0)
    spacing = float(voxel_size)
    if not np.isfinite(spacing) or spacing <= 0.0:
        raise ValueError("voxel_size must be a finite positive number")
    if blend_radius is None:
        blend_radius = 0.25 * minimum_radius
    blend_radius = float(blend_radius)
    if union_mode == "hard":
        blend_radius = 0.0
    elif not np.isfinite(blend_radius) or blend_radius <= 0.0:
        raise ValueError("blend_radius must be positive for a smooth union")

    padding = maximum_radius + blend_radius + 2.0 * spacing
    origin = np.minimum(np.min(p0, axis=0), np.min(p1, axis=0)) - padding
    upper = np.maximum(np.max(p0, axis=0), np.max(p1, axis=0)) + padding
    grid_shape = tuple(
        np.maximum(3, np.ceil((upper - origin) / spacing).astype(np.int64) + 1))
    tiles, reference_count = _tile_index(
        p0, p1, r0, r1, origin, grid_shape, spacing, int(tile_cells),
        blend_radius, int(max_tile_references))
    if verbose:
        print(f"Sparse union: {len(p0):,} segments, {len(tiles):,} active "
              f"tiles, {reference_count:,} tile references", flush=True)

    if tile_workers is None:
        tile_workers = min(8, os.cpu_count() or 1)
    tile_workers = int(tile_workers)
    if tile_workers < 1:
        raise ValueError("tile_workers must be at least 1")

    output = Path(ofile)
    output.parent.mkdir(parents=True, exist_ok=True)
    boundary_vertices = {}
    vertex_count = 0
    face_count = 0
    surface_tiles = 0
    report_every = max(1, min(25_000, len(tiles) // 100))

    def evaluate_tile(item):
        tile, segment_indices = item
        cell_start = np.asarray(tile, dtype=np.int64) * tile_cells
        cell_stop = np.minimum(
            cell_start + tile_cells,
            np.asarray(grid_shape, dtype=np.int64) - 1)
        cell_shape = cell_stop - cell_start
        if np.any(cell_shape <= 0):
            return None
        shape = tuple(int(value + 1) for value in cell_shape)
        tile_origin = origin + cell_start * spacing
        field = np.full(shape, np.float32(np.inf), dtype=np.float32)
        for segment_index in segment_indices:
            _update_union(
                field, tile_origin, spacing,
                p0[segment_index], p1[segment_index],
                float(r0[segment_index]), float(r1[segment_index]),
                union_mode=union_mode, blend_radius=blend_radius)
        finite = np.isfinite(field)
        if not np.any(finite):
            return None
        field[~finite] = maximum_radius + blend_radius + 2.0 * spacing
        if np.min(field) > 0.0 or np.max(field) < 0.0:
            return None
        vertices, faces, _, _ = marching_cubes(
            field, level=0.0, spacing=(spacing,) * 3,
            allow_degenerate=False)
        return tile, cell_shape, vertices, faces

    with tempfile.TemporaryDirectory(prefix="pymira_tiled_mesh_") as temp_dir:
        vertex_path = Path(temp_dir) / "vertices.bin"
        face_path = Path(temp_dir) / "faces.bin"
        with open(vertex_path, "wb") as vertex_stream, \
                open(face_path, "wb") as face_stream:
            executor = ThreadPoolExecutor(max_workers=tile_workers)
            try:
                results = _bounded_parallel_map(
                    executor, evaluate_tile, tiles.items(),
                    max_pending=max(2, tile_workers * 2))
                for visited, result in enumerate(results, start=1):
                    if verbose and visited % report_every == 0:
                        print(
                            f"Sparse union: visited {visited:,}/{len(tiles):,} "
                            f"active tiles ({surface_tiles:,} surface tiles)",
                            flush=True)
                    if result is None:
                        continue
                    tile, cell_shape, vertices, faces = result
                    cell_start = np.asarray(tile, dtype=np.int64) * tile_cells
                    tile_origin = origin + cell_start * spacing
                    local_grid = vertices / spacing
                    global_grid = local_grid + cell_start
                    world_vertices = (vertices + tile_origin).astype("<f4")
                    local_to_global = np.empty(len(vertices), dtype=np.int64)
                    new_vertices = []
                    for local_index in range(len(vertices)):
                        key = _boundary_key(
                            global_grid[local_index], local_grid[local_index],
                            cell_shape)
                        if key is not None and key in boundary_vertices:
                            local_to_global[local_index] = boundary_vertices[key]
                            continue
                        if vertex_count >= np.iinfo(np.int32).max:
                            raise OverflowError(
                                "PLY vertex count exceeds signed int32")
                        local_to_global[local_index] = vertex_count
                        if key is not None:
                            boundary_vertices[key] = vertex_count
                        new_vertices.append(world_vertices[local_index])
                        vertex_count += 1
                    if new_vertices:
                        np.asarray(new_vertices, dtype="<f4").tofile(
                            vertex_stream)

                    global_faces = local_to_global[faces]
                    valid = ((global_faces[:, 0] != global_faces[:, 1]) &
                             (global_faces[:, 1] != global_faces[:, 2]) &
                             (global_faces[:, 2] != global_faces[:, 0]))
                    global_faces = global_faces[valid].astype(
                        "<i4", copy=False)
                    records = np.empty(len(global_faces), dtype=_FACE_DTYPE)
                    records["count"] = 3
                    records["indices"] = global_faces
                    records.tofile(face_stream)
                    face_count += len(global_faces)
                    surface_tiles += 1
            finally:
                executor.shutdown(wait=True, cancel_futures=True)

        _write_binary_ply(
            output, vertex_path, face_path, vertex_count, face_count)

    result = {
        "vertices": vertex_count,
        "triangles": face_count,
        "active_tiles": len(tiles),
        "surface_tiles": surface_tiles,
        "tile_references": reference_count,
        "tile_workers": tile_workers,
        "voxel_size": spacing,
        "ofile": str(output),
    }
    if verbose:
        print(f"Mesh written to {output} ({vertex_count:,} vertices, "
              f"{face_count:,} triangles)", flush=True)
    return result
